function normalizeLanguage(value: string | null): Language {
  if (value === 'en' || value === 'es') return value;
  return 'pt';
}

function storedLanguage(): Language {
  if (typeof window === 'undefined') return 'pt';
  try {
    const email = JSON.parse(localStorage.getItem('currentUser') || 'null');
    if (email) {
      const preferences = JSON.parse(localStorage.getItem(`preferences_${String(email).trim().toLowerCase()}`) || '{}');
      if (preferences.language) return normalizeLanguage(preferences.language);
    }
  } catch { /* fallback global abaixo */ }
  return normalizeLanguage(localStorage.getItem(STORAGE_KEY));
}

function translateText(value: string, language: Language): string {
  if (language === 'pt') return value;
  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) return value;
  const content = match[2];
  const translated = dictionary[content]?.[language];
  if (translated) return `${match[1]}${translated}${match[3]}`;
  const templates: Array<[RegExp, (groups: RegExpMatchArray) => string]> = [
    [/^(\d+) conta\(s\)$/, groups => language === 'en' ? `${groups[1]} account(s)` : `${groups[1]} cuenta(s)`],
    [/^(\d+) registro\(s\)$/, groups => language === 'en' ? `${groups[1]} record(s)` : `${groups[1]} registro(s)`],
    [/^(\d+) agendamento\(s\)$/, groups => language === 'en' ? `${groups[1]} appointment(s)` : `${groups[1]} cita(s)`],
    [/^(\d+) aula(?:s)?$/, groups => language === 'en' ? `${groups[1]} class(es)` : `${groups[1]} clase(s)`],
    [/^este horário possui (\d+) aluno\(s\)$/, groups => language === 'en' ? `this time has ${groups[1]} student(s)` : `este horario tiene ${groups[1]} alumno(s)`],
    [/^Idioma salvo: (.+)$/, groups => language === 'en' ? `Language saved: ${groups[1]}` : `Idioma guardado: ${groups[1]}`],
    [/^Status alterado para (.+)\.$/, groups => language === 'en' ? `Status changed to ${groups[1]}.` : `Estado cambiado a ${groups[1]}.`],
  ];
  for (const [pattern, render] of templates) {
    const dynamicMatch = content.match(pattern);
    if (dynamicMatch) return `${match[1]}${render(dynamicMatch)}${match[3]}`;
  }
  return value;
}

const Context = createContext({ language: 'pt' as Language, setLanguage: (_language: Language) => {}, t: (value: string) => value });
const textOriginals = new WeakMap<Node, string>();

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setState] = useState<Language>(storedLanguage);
  const setLanguage = (next: Language) => {
    localStorage.setItem(STORAGE_KEY, next);
    try {
      const email = JSON.parse(localStorage.getItem('currentUser') || 'null');
      if (email) {
        const key = `preferences_${String(email).trim().toLowerCase()}`;
        const preferences = JSON.parse(localStorage.getItem(key) || '{}');
        localStorage.setItem(key, JSON.stringify({ ...preferences, language: next }));
      }
    } catch { /* preferência global continua válida */ }
    document.documentElement.lang = next === 'pt' ? 'pt-BR' : next;
    setState(next);
    window.dispatchEvent(new CustomEvent('pilamanager:language-changed', { detail: next }));
  };
  useEffect(() => { document.documentElement.lang = language === 'pt' ? 'pt-BR' : language; }, [language]);
  useEffect(() => {
    const syncUserLanguage = () => {
      const next = storedLanguage();
      document.documentElement.lang = next === 'pt' ? 'pt-BR' : next;
      setState(next);
    };
    window.addEventListener('pilamanager:user-changed', syncUserLanguage);
    return () => window.removeEventListener('pilamanager:user-changed', syncUserLanguage);
  }, []);
  const value = useMemo(() => ({ language, setLanguage, t: (text: string) => translateText(text, language) }), [language]);
  return <Context.Provider value={value}>{children}<GlobalTranslationObserver language={language} /></Context.Provider>;
}

export function useI18n() { return useContext(Context); }

function GlobalTranslationObserver({ language }: { language: Language }) {
  useEffect(() => {
    const attributes = ['placeholder', 'title', 'aria-label'] as const;
    const scan = (root: Node) => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
      let node: Node | null = root;
      while (node) {
        if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
          const original = textOriginals.get(node) ?? node.nodeValue;
          textOriginals.set(node, original);
          const translated = translateText(original, language);
          if (node.nodeValue !== translated) node.nodeValue = translated;
        } else if (node instanceof HTMLElement) {
          for (const attribute of attributes) {
            const current = node.getAttribute(attribute);
            if (!current) continue;
            const key = `data-i18n-${attribute}`;
            const original = node.getAttribute(key) ?? current;
            node.setAttribute(key, original);
            const translated = translateText(original, language);
            if (current !== translated) node.setAttribute(attribute, translated);
          }
        }
        node = walker.nextNode();
      }
    };
    scan(document.body);
    const observer = new MutationObserver(records => records.forEach(record => {
      record.addedNodes.forEach(scan);
      if (record.type === 'characterData' && record.target.nodeValue) {
        const original = textOriginals.get(record.target);
        const current = record.target.nodeValue;
        const known = original && (current === original || current === translateText(original, 'en') || current === translateText(original, 'es'));
        if (!known) textOriginals.set(record.target, current);
        scan(record.target);
      }
    }));
    observer.observe(document.body, { childList: true, characterData: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);
  return null;
}
